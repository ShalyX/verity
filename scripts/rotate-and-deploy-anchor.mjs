import fs from "node:fs";
import solc from "solc";
import { ContractFactory, JsonRpcProvider, Wallet, parseEther } from "ethers";
const file = ".env.local";
const lines = fs.readFileSync(file, "utf8").split(/\r?\n/);
const get = (name) => lines.find((line) => line.startsWith(`${name}=`))?.slice(name.length + 1).trim();
const rpc = get("ZG_CHAIN_RPC_URL");
const oldKey = get("ZG_DEPLOYER_PRIVATE_KEY");
if (!rpc || !/^0x[0-9a-fA-F]{64}$/.test(oldKey || "")) throw new Error("MISSING_OLD_SIGNER");
const provider = new JsonRpcProvider(rpc);
const oldWallet = new Wallet(oldKey, provider);
const fresh = Wallet.createRandom().connect(provider);
const funding = await oldWallet.sendTransaction({ to: fresh.address, value: parseEther("0.05") });
await funding.wait();
const source = fs.readFileSync("contracts/VerityReceiptAnchor.sol", "utf8");
const input = { language: "Solidity", sources: { "VerityReceiptAnchor.sol": { content: source } }, settings: { optimizer: { enabled: true, runs: 200 }, outputSelection: { "*": { "*": ["abi", "evm.bytecode"] } } } };
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const artifact = output.contracts["VerityReceiptAnchor.sol"].VerityReceiptAnchor;
const deployed = await new ContractFactory(artifact.abi, artifact.evm.bytecode.object, fresh).deploy();
const receipt = await deployed.deploymentTransaction().wait();
const address = await deployed.getAddress();
const kept = lines.filter((line) => line && !line.startsWith("ZG_DEPLOYER_PRIVATE_KEY=") && !line.startsWith("ZG_STORAGE_PRIVATE_KEY=") && !line.startsWith("ZG_RECEIPT_CONTRACT_ADDRESS="));
kept.push(`ZG_DEPLOYER_PRIVATE_KEY=${fresh.privateKey}`, `ZG_STORAGE_PRIVATE_KEY=${fresh.privateKey}`, `ZG_RECEIPT_CONTRACT_ADDRESS=${address}`);
fs.writeFileSync(file, kept.join("\n") + "\n", { mode: 0o600 });
console.log(JSON.stringify({ address, deployTx: receipt.hash, block: receipt.blockNumber, fundingTx: funding.hash, signer: fresh.address }));
